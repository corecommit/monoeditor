    fun forSymbol(s: Symbol): String {
        val byHeader = TABLE["${s.header}:${s.name}"]
        if (byHeader != null) return byHeader
        if (s.container.isNotEmpty() && s.container != "std") {
            TABLE["${s.container}.${s.name}"]?.let { return it }
        }
        TABLE[s.name]?.let { return it }
        return when (s.kind) {
            SymKind.CLASS, SymKind.STRUCT -> "standard library type"
            SymKind.FUNCTION -> "standard library function"
            SymKind.MEMBER, SymKind.METHOD ->
                if (s.container.isNotEmpty() && s.container != "std") "member of ${s.container}" else "standard library member"
            SymKind.MACRO -> "macro"
            else -> ""
        }
    }

