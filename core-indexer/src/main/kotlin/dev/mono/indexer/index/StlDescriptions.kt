/**
 * One-line descriptions for the curated standard-library index, shown under
 * each autocomplete row. Lookup order for a symbol:
 *  1. "header:name"      (same name in different headers, e.g. unistd.h:read)
 *  2. "container.name"   (member of a class, e.g. unique_ptr.get)
 *  3. "name"
 * then a generic fallback by kind.
